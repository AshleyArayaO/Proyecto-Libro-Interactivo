    public void mostrarPreguntas(
            String titulo,
            String contenido,
            String[] preguntas,
            String[][] opciones) {

        lbltitulo.setText(titulo);
        lblIndicacion.setText(contenido);

        lblPregunta1.setText(preguntas[0]);
        lblPregunta2.setText(preguntas[1]);
        lblPregunta3.setText(preguntas[2]);

        r1op1.setText(opciones[0][0]);
        r1op2.setText(opciones[0][1]);
        r1op3.setText(opciones[0][2]);

        r2op1.setText(opciones[1][0]);
        r2op2.setText(opciones[1][1]);
        r2op3.setText(opciones[1][2]);

        r3op1.setText(opciones[2][0]);
        r3op2.setText(opciones[2][1]);
        r3op3.setText(opciones[2][2]);
    }

    public int[] obtenerRespuestas() {

        int[] respuestas = new int[3];

        respuestas[0] = obtenerSeleccion(r1op1, r1op2, r1op3);
        respuestas[1] = obtenerSeleccion(r2op1, r2op2, r2op3);
        respuestas[2] = obtenerSeleccion(r3op1, r3op2, r3op3);

        return respuestas;
    }

    private int obtenerSeleccion(
            AbstractButton op1,
            AbstractButton op2,
            AbstractButton op3) {

        if (op1.isSelected()) {
            return 1;
        }

        if (op2.isSelected()) {
            return 2;
        }

        if (op3.isSelected()) {
            return 3;
        }

        return 0;
    }

